import { barBeats, canRampBetween, progressionBeats, type PlaybackSegment } from "./model";

/** Темп і розмір, у яких транспорт перебуває ЗАРАЗ. `null` — ще нічого не грало. */
export interface TempoState {
  bpm: number;
  timeSignature: [number, number];
}

export interface TempoTransition {
  /**
   * Скільки імпульсів у такті — рівно те, що транспорт зве `timeSignature`.
   * Пара `[num, den]` йому не годиться: він порахував би 6/8 як три чверті,
   * тоді як у нашій моделі це шість імпульсів (див. `setupTransport`).
   */
  barBeats: number;
  bpm: number;
  /** Скільки секунд вести темп. `0` — стрибок рівно на межі. */
  rampSeconds: number;
}

/**
 * @param from темп і розмір попереднього сегмента; `null` для першого.
 */
export const planTempoTransition = (
  from: TempoState | null,
  segment: PlaybackSegment,
): TempoTransition => {
  const plan: TempoTransition = {
    barBeats: barBeats(segment.timeSignature),
    bpm: segment.bpm,
    rampSeconds: 0,
  };

  // Рампити нема ЗВІДКИ без попереднього, нема КУДИ при тому самому темпі,
  // нема ЧИМ при різних знаменниках (BPM рахує імпульси, а імпульс у 4/4 і в
  // 6/8 — різні одиниці) і нема ДЕ в порожньому сегменті.
  if (segment.rampTempo !== true) return plan;
  if (from == null || from.bpm === segment.bpm) return plan;
  if (!canRampBetween(from.timeSignature, segment.timeSignature)) return plan;

  const passBeats = progressionBeats(segment.progression);
  if (passBeats <= 0) return plan;

  // Довжина рампу — рівно один прохід сегмента, а прохід міряється в
  // ІМПУЛЬСАХ, тоді як Tone веде параметр у СЕКУНДАХ. Переводимо по середньому
  // темпу: за час рампу транспорт проходить стільки імпульсів, скільки дає
  // середній темп.
  //
  // ⚠️ Середнє АРИФМЕТИЧНЕ країв — це середній темп лише при ЛІНІЙНОМУ
  // веденні. Тому плеєр і мусить кликати `linearRampTo`, а не Tone-ове
  // `rampTo`, яке на одиницях `bpm` веде експонентою (там середній темп —
  // логарифмічний, тобто менший, і рамп добігав би до цілі раніше за коло).
  const averageBpm = (from.bpm + segment.bpm) / 2;
  if (averageBpm <= 0) return plan;

  return { ...plan, rampSeconds: (passBeats * 60) / averageBpm };
};
