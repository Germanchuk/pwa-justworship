import type { AudioHostPlaybackState } from "#modules/Band/audio/types";

/**
 * ЧОМУ ТИХО — одне правило на весь екран зібрання (`PLAY-30`).
 *
 * Тиша посеред служіння читається однаково погано, з якої б причини вона не
 * сталась: натиснув «грати», і нічого. Тому питання тут одне («звучить чи
 * ні?»), а причин кілька, і порядок між ними — теж рішення:
 *
 *   1. **невдалий запуск** — найсвіжіша подія: людина щойно тиснула, і саме
 *      цей натиск не спрацював;
 *   2. **грати нічого** — стан самого служіння, він сильніший за все, що
 *      стосується хоста: у списку без жодного звучного пункту хост теж не
 *      заграє;
 *   3. **хост мовчить** — команда пішла, а звук у залі не піднявся.
 *
 * Порожнє служіння (жодного пункту) з цього списку виходить: про нього екран
 * і так пише окремо, і два написи про одне сказали б, що застосунок сам себе
 * не розуміє.
 *
 * ⚠️ «Тихо» тут — це стан **того маршруту, який зараз мій** (`routeFor`):
 * граю сам — свій стан, командую хостом — його. Інакше напис про мовчазного
 * хоста висів би під власний звук із динаміка.
 *
 * Чиста функція навмисно: тайминг («скільки чекати хоста») — справа екрана, а
 * ЩО з цього випливає перевіряється таблицею.
 */
export type SilenceReason = "startFailed" | "empty" | "hostSilent";

export interface SilenceInput {
  /**
   * Стан того пристрою, який грає МОЄ служіння, — свій або хостовий.
   *
   * ⚠️ `loading` — це НЕ тиша, а дорога: між командою і звуком стоїть
   * завантаження семплів (а на хості ще й читання служіння). Пояснювати там
   * нема чого, і саме тому воно тут не окремий випадок, а просто «не idle».
   */
  state: AudioHostPlaybackState;
  /** Скільки пунктів у служінні взагалі. */
  itemCount: number;
  /** Скільки з них звучать: `0` — грати нічого. */
  segmentCount: number;
  /** Остання спроба запуску на цьому пристрої впала. */
  startFailed: boolean;
  /** Хоста попросили грати, і минув час, за який він мав озватись. */
  hostLate: boolean;
}

export const silenceReason = ({
  state,
  itemCount,
  segmentCount,
  startFailed,
  hostLate,
}: SilenceInput): SilenceReason | null => {
  if (state !== "idle") return null;
  if (startFailed) return "startFailed";
  if (itemCount === 0) return null;
  if (segmentCount === 0) return "empty";
  if (hostLate) return "hostSilent";
  return null;
};
