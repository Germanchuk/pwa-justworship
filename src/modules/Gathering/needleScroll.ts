/**
 * КУДИ ВЕЗТИ ЕКРАН — уся арифметика автоскролу, без DOM і React.
 *
 * Голка спільна, скрол особистий (`LIST-44`): що звучить, вирішує хост, а де
 * воно опинилось на моєму екрані — залежить від мого капо, моїх фільтрів,
 * згорнутих секцій і розміру мого телефона. Тому сюди приходить уже виміряна
 * позиція голки, а не її ключ: усе перелічене вимірюється саме собою, коли
 * читаєш рамку елемента (`useNeedleScroll`).
 *
 * ─── ДВІ МЕЖІ, А НЕ ОДНА ───────────────────────────────────────────────────
 * Наївний `scrollIntoView` на кожен акорд возить екран безперервно: голка
 * рухається кілька разів на такт, і рядок під пальцями ніколи не стоїть на
 * місці. Тому меж дві:
 *
 *   ЯКІР — куди ставимо голку, КОЛИ вже вирішили везти. Третина висоти під
 *   баром: над голкою лишається щойно зігране (я міг відстати), під нею —
 *   дві третини того, що буде.
 *
 *   КОМФОРТ — доки голка вище цієї межі, екран НЕ рухається взагалі. Звідси
 *   рух виходить рідким і великим: разів зо два на секцію, а не по піксельчику
 *   на акорд.
 *
 * Голка вище смуги — теж привід везти: так буває на новому проході лупа
 * програша й на початку наступної пісні, і саме тоді треба вернутись угору.
 */

/** Голка, вікно й документ — усе, що треба знати, щоб вирішити. */
export interface NeedleFrame {
  /** Верх голки відносно вікна (як у `getBoundingClientRect`). */
  top: number;
  /** Низ голки відносно вікна. */
  bottom: number;
  /** Висота вікна. */
  viewport: number;
  /** Скільки зверху затуляє липкий бар. Схований бар — нуль. */
  headroom: number;
  /** Поточний скрол сторінки. */
  scrollTop: number;
  /** Найбільший можливий скрол: висота документа мінус вікно. */
  maxScrollTop: number;
}

/** Частка вільної смуги, на якій стоїть голка після переїзду. */
const ANCHOR = 0.3;

/** Доки голка вище цієї частки вільної смуги — екран стоїть. */
const COMFORT = 0.66;

/**
 * Менший зсув не робимо: браузер усе одно смикне екран, а голка від цього
 * рівніше не стане.
 */
const MIN_STEP = 2;

const clamp = (value: number, min: number, max: number): number =>
  Math.min(max, Math.max(min, value));

/**
 * Новий `scrollTop`, або `null` — «стій, де стоїш».
 *
 * `force` — це кнопка «до голки»: людина попросила явно, тож комфортна смуга
 * не рахується. Не рахується вона й тоді, коли їхати нікуди: у кінці документа
 * голка може лишитись низько, і краще стояти, ніж смикатись на кожен акорд.
 */
export const needleScrollTop = (
  frame: NeedleFrame,
  { force = false }: { force?: boolean } = {},
): number | null => {
  const free = frame.viewport - frame.headroom;
  if (free <= 0) return null;

  if (!force) {
    const comfortable =
      frame.top >= frame.headroom && frame.bottom <= frame.headroom + free * COMFORT;
    if (comfortable) return null;
  }

  const anchor = frame.headroom + free * ANCHOR;
  const target = clamp(
    Math.round(frame.scrollTop + frame.top - anchor),
    0,
    frame.maxScrollTop,
  );

  return Math.abs(target - frame.scrollTop) < MIN_STEP ? null : target;
};
