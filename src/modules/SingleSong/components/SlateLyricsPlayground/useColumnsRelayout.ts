import { useCallback, useEffect, useRef, type RefObject } from "react";

/** Пауза в наборі, після якої скидаємо розбиття на колонки. */
const IDLE_MS = 200;

/**
 * Обхід баґа Chrome: після правки ПОСЕРЕД пісні верхні рядки наступних
 * колонок наїжджають один на одного.
 *
 * Що відбувається. На широких екранах редактор — це multicol із прибитою
 * висотою (див. `SlateLyricsPlayground.css`). Коли посеред пісні зʼявляються
 * нові рядки, весь вміст нижче переїжджає в інші колонки. Chrome оновлює
 * розбиття інкрементно і лишається з неузгодженим станом: `getClientRects`
 * дає правильні координати рядків, а малює він їх за старим розбиттям — по
 * кілька рядків в одному місці.
 *
 * Чому це браузер, а не ми. Відтворюється на голій HTML-сторінці з цим самим
 * CSS — без React, Slate і contenteditable: досить додавати по одному
 * порожньому `div` посеред multicol. У зламаному кадрі DOM рівно збігається з
 * моделлю (осиротілих чи дубльованих вузлів немає), а таблиця координат від
 * самого браузера не збігається з тим, що намальовано. Chrome 152, macOS.
 *
 * Чому саме перемикання display. Стан НЕ лікує ні зміна
 * `--song-column-height`, ні `column-width`, ні `column-fill`, ні
 * `opacity`/`filter`/`will-change`/`content-visibility`, ні горизонтальний
 * скрол, ні `overflow: visible` замість скролера, ні `display: block` замість
 * `inline-block` на `.chord-line` — усе перевірено. Скидає його лише
 * перебудова дерева розкладки.
 *
 * Ціна: один перерахунок розкладки редактора (~10 мс на сотню рядків) на
 * паузу в наборі, а не на кожну зміну. Рух каретки сюди не доходить —
 * `onValueChange` на нього не спрацьовує. Каретку, фокус і горизонтальну
 * прокрутку перемикання не чіпає: вузол лишається в DOM (перевірено).
 *
 * Знімається одним файлом: коли Chrome це полагодить або коли колонки
 * поїдуть із редактора — видалити цей модуль і `onValueChange` у
 * `SlateLyricsPlayground.tsx`, більше він нікуди не вплетений. Перевірити
 * можна мінімальним відтворенням (див. коміт, у якому зʼявився цей файл).
 *
 * Повертає колбек для `<Slate onValueChange>`.
 */
export function useColumnsRelayout(ref: RefObject<HTMLElement | null>) {
  const timerRef = useRef(0);

  useEffect(() => () => clearTimeout(timerRef.current), []);

  return useCallback(() => {
    // Вузькі екрани малюють пісню одним стовпцем — ламатись нема чому.
    // Умова дублює медіа-запит із SlateLyricsPlayground.css.
    if (!window.matchMedia("(min-width: 768px)").matches) return;

    // Перерахунок коштує ~10 мс на пісню в сотню рядків, тобто цілий кадр.
    // Робити його на кожну літеру — це гарантовано рвана анімація набору,
    // тому чекаємо паузи. Зіпсоване розбиття видно в НАСТУПНИХ колонках, не
    // там, де каретка, тож поки людина друкує, вона його й не дивиться.
    clearTimeout(timerRef.current);
    timerRef.current = window.setTimeout(() => {
      const el = ref.current;
      if (!el) return;
      const prev = el.style.display;
      el.style.display = "none";
      // Читання змушує браузер викинути стару розкладку тут і зараз — без
      // цього рядка обидві зміни стилю злипнуться в одну й нічого не дадуть.
      void el.offsetHeight;
      el.style.display = prev;
    }, IDLE_MS);
  }, [ref]);
}
