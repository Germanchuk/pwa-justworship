/**
 * ── Модель часу ─────────────────────────────────────────────────────────────
 *
 * Одиниця музичного часу в застосунку — **імпульс**: рівно те, що коштує одна
 * крапка `.` в акордовому рядку. Імпульс = одиниця знаменника розміру:
 * у 4/4 і 3/4 це чверть, у 6/8 — вісімка.
 *
 * З цього випливають два правила, на яких тримається весь плеєр:
 *
 *   1. Такт = `чисельник` імпульсів. `| C . . G . . |` — повний такт 6/8.
 *   2. **BPM рахує імпульси**: один імпульс завжди триває `60 / bpm` секунд,
 *      у будь-якому розмірі. Тому пісня в 6/8 записується темпом вісімок
 *      (~150–200), а не чвертей із крапкою.
 *
 * Наслідок для коду: імпульс лягає 1:1 на чверть транспорту Tone, тож усе
 * планування (тіки, таймлайн підсвітки, вступний відлік) рахує імпульси й
 * знаменника не знає взагалі. Поза цим файлом знаменник впливає рівно на одне —
 * на стелю слайдера BPM: темп вісімками потребує більшого діапазону.
 */
