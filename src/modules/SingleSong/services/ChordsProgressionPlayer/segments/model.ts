/**
 * СЕГМЕНТИ ПЛЕЙБЕКУ — точка розуміння.
 *
 * Плеєр більше не грає «одну пісню від початку до кінця». Він грає **чергу
 * сегментів**, дописуючи їх у живий транспорт перед голкою («рулонний» режим).
 * Пісня — окремий випадок: черга з одного сегмента типу `once`.
 *
 * ─── НАВІЩО ────────────────────────────────────────────────────────────────
 * Режим зібрання грає все служіння одним безшовним плейбеком: пісня → програш
 * → пісня. Програш крутиться невідому кількість разів (поки говорить ведучий),
 * тож увесь MIDI наперед побудувати неможливо в принципі. Звідси рулон.
 *
 * ─── ЧОМУ ЦЕ ВЗАГАЛІ ПРАЦЮЄ ────────────────────────────────────────────────
 * Тому що весь таймінг у застосунку живе в **тіках**, а не в секундах
 * (`beatsToTicks`, `midiToPartEvents` читає `n.ticks`, не `n.time`). Наслідок:
 * темп можна міняти будь-коли, і вже заплановані ноти лишаються музично
 * правильними. Саме це робить можливим і плавний перехід темпу між піснями, і
 * зміну розміру на межі сегмента.
 *
 * ─── ОДИНИЦЯ ЧАСУ ──────────────────────────────────────────────────────────
 * Скрізь тут — **імпульс** (те, що коштує одна крапка `.` в акордовому рядку,
 * і водночас одиниця знаменника розміру). Секунд у цьому шарі немає взагалі:
 * імпульс → тік робить шар Tone, і робить це один раз. Див. `songDefaults.ts`.
 */

import type { ChordEvent } from "../getMidiFromSections/utils/createMidiFromProgression";

/**
 * Що сегмент робить, дійшовши до свого кінця.
 *
 *   once  — прозвучав і поступився наступному. Пісня, вступ програша, вихід.
 *   loop  — повторюється, доки ззовні не попросять вийти (`requestLoopExit`).
 *           Це «поки говорить ведучий»: скільки саме — не знає ніхто.
 *   pause — дійшов і став: справжня зупинка транспорту, далі лише з команди.
 *           Це примітка без програша: там говорить ведучий, і музики немає.
 *
 * ⚠️ `pause` має НУЛЬОВУ довжину, а `pullPasses` мовчки пропускає нульові
 * сегменти (захист від нескінченного циклу планувальника). Черга навчиться
 * бачити паузу до цієї перевірки в тікеті `06`; доти зібрання проминає
 * примітки, і це свідомий проміжний стан, а не забутий баг.
 */
export type SegmentKind = "once" | "loop" | "pause";

export interface PlaybackSegment {
  /** Стабільний ідентифікатор — щоб слухачі розуміли, що зараз звучить. */
  id: string;
  /** Прогресія в імпульсах. Береться з лексера акордів — того самого, що й у пісні. */
  progression: ChordEvent[];
  /** Темп сегмента в імпульсах за хвилину. */
  bpm: number;
  timeSignature: [number, number];
  kind: SegmentKind;
  /**
   * Префікс, з яким ключі токенів цього сегмента виходять назовні.
   *
   * У зібранні один і той самий `sectionIndex:рядок:токен` існує в КОЖНІЙ
   * пісні служіння, тож без префікса пункту той самий ключ спалахнув би одразу
   * в кількох. Префікс живе на сегменті, а не в опціях розкладки, бо їде по
   * мережі разом з голкою — це частина протоколу, а не деталь рендера
   * (ADR-0001). На сторінці пісні його немає, і протокол лишається тим самим.
   */
  tokenKeyPrefix?: string;
  /**
   * Плавно перевести темп від темпу попереднього сегмента до свого **за один
   * свій прохід** (рішення Германа 2026-08-17 про програш). Далі сегмент
   * лишається на своєму `bpm`.
   *
   * ⚠️ Рампити можна лише коли знаменник не змінюється. BPM рахує імпульси,
   * тож 4/4@80 → 6/8@168 — це музично СПОВІЛЬНЕННЯ відчутної долі (80 → 56),
   * і наївний рамп поїхав би в протилежний бік. Перевірку робить
   * `canRampBetween`.
   */
  rampTempo?: boolean;
}

/**
 * Ключ токена, яким його знає весь застосунок: свій у межах пісні, з префіксом
 * пункту — у межах зібрання. Єдине місце, де ці дві форми зшиваються.
 */
export const prefixTokenKey = (
  tokenKey: string | null,
  prefix: string | undefined,
): string | null => {
  if (tokenKey == null) return null;
  return prefix ? `${prefix}:${tokenKey}` : tokenKey;
};

/**
 * Зворотний бік: чи цей ключ належить ЦЬОМУ пунктові, і яким він там є.
 *
 * `null` означає «не мій» — і саме на цьому стоїть правило «підсвітка не
 * спалахує в кількох піснях одразу»: документ пункту знає лише свої ключі
 * (`секція:рядок:токен`), а той самий ключ існує в кожній пісні служіння.
 * Двокрапка в порівнянні обов'язкова: без неї `p1` впізнав би `p10`.
 */
export const unprefixTokenKey = (
  tokenKey: string | null,
  prefix: string | undefined,
): string | null => {
  if (tokenKey == null) return null;
  if (!prefix) return tokenKey;
  const head = `${prefix}:`;
  return tokenKey.startsWith(head) ? tokenKey.slice(head.length) : null;
};

/** Нота, готова до планування: час в **абсолютних імпульсах** від старту транспорту. */
export interface PlannedNote {
  beats: number;
  durationBeats: number;
  /** MIDI-номер. У назву ноти його переводить шар Tone — тут Tone немає. */
  midi: number;
  velocity: number;
}

/** Подія підсвітки: той самий абсолютний час, плюс ключ токена в редакторі. */
export interface PlannedChord {
  beats: number;
  durationBeats: number;
  chord: string | null;
  /**
   * `${sectionIndex}:${chordLineIndex}:${tokenIndex}` у межах сегмента, з
   * префіксом пункту попереду, коли грає зібрання — див. `prefixTokenKey`.
   */
  tokenKey: string | null;
}

/** Один прохід сегмента, розкладений в абсолютний час. */
export interface PlannedPass {
  segmentId: string;
  /** Абсолютний імпульс, з якого прохід починається. */
  startBeats: number;
  /** Довжина проходу в імпульсах. */
  lengthBeats: number;
  notes: PlannedNote[];
  chords: PlannedChord[];
}

/**
 * Чи можна плавно вести темп від одного сегмента до іншого.
 *
 * Можна лише при однаковому знаменнику: BPM рахує імпульси, а імпульс у 4/4 і
 * в 6/8 — різні одиниці. Рамп між ними міняв би не ту величину (див. `rampTempo`).
 * Коли не можна — темп перемикається стрибком на межі сегмента, і чистий злам
 * читається як задум, а не як помилка.
 */
export const canRampBetween = (
  from: [number, number] | null,
  to: [number, number],
): boolean => from != null && from[1] === to[1];

/**
 * Довжина такту в імпульсах — це чисельник розміру. Знаменник тут не бере
 * участі: він задає, ЧИМ ми міряємо, а не скільки їх у такті.
 */
export const barBeats = (timeSignature: [number, number]): number => timeSignature[0];

/** Сумарна довжина прогресії в імпульсах. */
export const progressionBeats = (progression: ChordEvent[]): number =>
  progression.reduce((sum, event) => sum + Math.max(0, event.duration || 0), 0);
