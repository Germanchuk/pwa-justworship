/**
 * Символи акордового рядка, які не є акордами.
 *
 * Живуть окремо, бо потрібні по обидва боки: і лексеру, що ріже рядок на такти,
 * і озвученню, що вирішує, чи має токен звучати. Один символ — одне значення,
 * жодних синонімів: різні написання того самого добре виглядають у документації
 * і погано — в чужому рядку, який треба прочитати з телефона за пів секунди.
 */

/**
 * Тиша — доля, у яку нічого не звучить. Такт лишається повним: `| C . _ . |`
 * у 4/4 — це дві долі «до», доля тиші й ще одна тиші (крапка продовжує тишу
 * так само, як продовжувала б акорд).
 *
 * Підкреслення обране за виглядом: порожнє місце в рядку. Воно не трапляється
 * в назвах акордів і не ріжеться токенізатором, тож правило «крапка = доля»
 * лишається без винятків.
 */
export const SILENCE_MARK = "_";

/**
 * Свідомо неповний такт: «такт закінчується тут, решти долей просто немає».
 * Протилежність тиші — тиша займає час і лишає такт повним, а ця позначка
 * такт обриває, і наступний починається раніше.
 *
 * Це **прапорець на весь такт**, а не заповнювач вилученої долі: одного досить,
 * позиція значення не має, довжину дає написане до нього. Саме тому символом
 * став `!`, а не `-`: рисочка виглядає як щось, що займає місце, і підказує
 * хибну модель «скільки долей прибрав, стільки й рисочок». Знак оклику ширини
 * не вдає — він вигукує, а не заповнює.
 */
export const INCOMPLETE_BAR_MARK = "!";
